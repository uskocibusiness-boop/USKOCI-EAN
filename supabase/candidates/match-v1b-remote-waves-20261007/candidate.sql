create function private.remote_wave_candidates_v1b(nid uuid, p_limit integer, p_cap integer)
 returns table(pid uuid, uid uuid, detail jsonb)
 language plpgsql
 stable security definer
 set search_path to 'pg_catalog'
as $mv1b_body$
declare
  n public.needs; found_n integer := 0; lo uuid; first_chunk boolean; got integer; r record; d jsonb;
  chunk constant integer := 500;
  zero constant uuid := '00000000-0000-0000-0000-000000000000';
begin
  -- MATCH-V1B (owner 2026-10-07): the next workers of the ROTATION of a task without a place, in the order of
  -- private.candidate_profile_ids (the profiles from the id of the task upwards, then the ones below it), but
  --   * a worker who was already notified for this revision of the task is skipped by an index probe, not by a full evaluation, so a
  --     wave costs the same whether 0 or 4,800 workers were notified before it (a worker is never notified twice for one revision);
  --   * a worker whose daily cap is reached is skipped without using up a place (p_cap null: no cap);
  --   * only workers who would really be notified are returned: the prefilter AND the detailed matcher agree (dispatchEligible),
  --     so a worker the detailed matcher refuses (a Dogovor in the window) can never hold up the workers behind him.
  -- The profiles are read in keyset chunks of 500 by profile id: an ordered index range, never a sort of all profiles.
  select * into n from public.needs where id = nid;
  if not found or p_limit is null or p_limit < 1 then return; end if;
  for phase in 1..2 loop
    lo := case when phase = 1 then n.id else zero end;
    first_chunk := true;
    loop
      got := 0;
      for r in
        select p.id as profile_id, p.account_id as account_id
          from public.app_profiles p
         where p.kind = 'WORKER' and p.profile_status = 'ACTIVE'
           and p.id >= lo and (first_chunk or p.id > lo)
           and (phase = 1 or p.id < n.id)
           and not exists (select 1 from public.opportunity_deliveries od
                            where od.worker_account_id = p.account_id and od.need_id = n.id and od.need_revision = n.revision)
         order by p.id
         limit chunk
      loop
        got := got + 1; lo := r.profile_id; first_chunk := false;
        if (p_cap is null or private.worker_notify_room_v1b(r.account_id, p_cap)) and private.dispatch_cheap_candidate_admitted(n.id, r.profile_id) then
          d := private.match_detail(n.id, r.profile_id);
          if coalesce((d->>'dispatchEligible')::boolean, false) then
            pid := r.profile_id; uid := r.account_id; detail := d;
            return next;
            found_n := found_n + 1;
            if found_n >= p_limit then return; end if;
          end if;
        end if;
      end loop;
      exit when got < chunk;
    end loop;
  end loop;
end;
