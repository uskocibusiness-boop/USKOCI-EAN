export function applyEdits(body) {
  for (const edit of edits) {
    if (body.split(edit.before).length !== 2) throw new Error(`P6_MIN_PRICE_ANCHOR_DRIFT: ${edit.name}`);
    body = body.replace(edit.before, edit.after);
  }
  return body;
}

export function buildCandidate() {
  if (digest(beforeBody) !== predecessor.body_md5) throw new Error('P6_MIN_PRICE_CAPTURE_DRIFT');
  const afterBody = applyEdits(beforeBody);
  return `-- LOCAL CANDIDATE ONLY. NOT APPLIED TO DEV. Not a migration registration.
-- Captured ${predecessor.checked_at}; project ${predecessor.project}; PG ${predecessor.postgres_version}.
-- Generated by build-candidate.mjs. Minimal STATED fixed price; preserves TOTAL/PER_PERSON basis.
begin;
set local lock_timeout='5s';
set local statement_timeout='30s';
do $p6_min_price$
declare target oid; body_before text; body_after text; definition_before text; meta_before jsonb; comment_before text; edit jsonb;
begin
 target:=to_regprocedure('public.rpc_discovery_v1(jsonb)');
 if target is null then raise exception 'P6_MIN_PRICE_FUNCTION_MISSING' using errcode='55000'; end if;
 select p.prosrc,to_jsonb(p)-'prosrc',obj_description(p.oid,'pg_proc') into strict body_before,meta_before,comment_before
 from pg_proc p where p.oid=target;
 if md5(body_before) is distinct from '${predecessor.body_md5}'
 then raise exception 'P6_MIN_PRICE_PREDECESSOR_DRIFT' using errcode='55000'; end if;
 if (select p.prosecdef or p.provolatile<>'s' or p.proowner<>'postgres'::regrole
    or p.proconfig is distinct from array['search_path=pg_catalog']
    or p.proacl::text is distinct from '{postgres=X/postgres,authenticated=X/postgres}' from pg_proc p where p.oid=target)
 then raise exception 'P6_MIN_PRICE_METADATA_DRIFT' using errcode='55000'; end if;
 body_after:=body_before;
 for edit in select value from jsonb_array_elements($p6_edits$${JSON.stringify(edits)}$p6_edits$::jsonb) loop
  if (length(body_after)-length(replace(body_after,edit->>'before','')))/length(edit->>'before')<>1
  then raise exception 'P6_MIN_PRICE_ANCHOR_DRIFT: %',edit->>'name' using errcode='55000'; end if;
  body_after:=replace(body_after,edit->>'before',edit->>'after');
 end loop;
 if md5(body_after) is distinct from '${digest(afterBody)}'
 then raise exception 'P6_MIN_PRICE_PAYLOAD_DRIFT' using errcode='55000'; end if;
 definition_before:=pg_get_functiondef(target);
 if (length(definition_before)-length(replace(definition_before,body_before,'')))/length(body_before)<>1
 then raise exception 'P6_MIN_PRICE_BODY_ANCHOR_DRIFT' using errcode='55000'; end if;
 execute replace(definition_before,body_before,body_after);
 if (select p.prosrc from pg_proc p where p.oid=target) is distinct from body_after
   or (select to_jsonb(p)-'prosrc' from pg_proc p where p.oid=target) is distinct from meta_before
   or obj_description(target,'pg_proc') is distinct from comment_before
 then raise exception 'P6_MIN_PRICE_POSTIMAGE_OR_METADATA_DRIFT' using errcode='55000'; end if;
end
$p6_min_price$;
commit;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1] && process.argv.includes('--write')) {
  writeFileSync(new URL('candidate.sql', directory), buildCandidate());
  console.log(JSON.stringify({ status: 'LOCAL_NOT_APPLIED', predecessor: predecessor.body_md5, candidate: digest(applyEdits(beforeBody)) }));
}
