def pins_block(label, pairs):
    return (" for r in select * from (values\n"
            + ",\n".join("  (" + quote(s) + "," + quote(m) + ")" for s, m in pairs)
            + ") pins(signature,body_md5) loop\n"
              "  if (select md5(p.prosrc) from pg_proc p where p.oid=to_regprocedure(r.signature)) is distinct from r.body_md5\n"
              "  then raise exception '" + label + ": %',r.signature using errcode='55000'; end if;\n"
              " end loop;\n")


def replace_block(source, target, label):
    return (" for r in select * from (values\n"
            + ",\n".join("  (" + quote(s) + "," + quote(md5(source[s])) + "," + quote(md5(target[s])) + "," + dollar(target[s]) + ")" for s in CHANGED)
            + ") patches(signature,before_md5,after_md5,new_body) loop\n"
              "  o:=to_regprocedure(r.signature);\n"
              "  if o is null then raise exception '" + label + "_MISSING_FUNCTION: %',r.signature using errcode='55000'; end if;\n"
              "  select p.prosrc,to_jsonb(p)-'prosrc',obj_description(p.oid,'pg_proc') into strict body,meta,comment_before from pg_proc p where p.oid=o;\n"
              "  if md5(body) is distinct from r.before_md5 then raise exception '" + label + "_PREIMAGE_DRIFT: %',r.signature using errcode='55000'; end if;\n"
              "  if md5(r.new_body) is distinct from r.after_md5 then raise exception '" + label + "_PAYLOAD_DRIFT: %',r.signature using errcode='55000'; end if;\n"
              "  def:=pg_get_functiondef(o);\n"
              "  if (length(def)-length(replace(def,body,'')))/length(body)<>1 then raise exception '" + label + "_BODY_ANCHOR_DRIFT: %',r.signature using errcode='55000'; end if;\n"
              "  execute replace(def,body,r.new_body);\n"
              "  if (select p.prosrc from pg_proc p where p.oid=o) is distinct from r.new_body\n"
              "   or (select to_jsonb(p)-'prosrc' from pg_proc p where p.oid=o) is distinct from meta\n"
              "   or obj_description(o,'pg_proc') is distinct from comment_before\n"
              "  then raise exception '" + label + "_POSTIMAGE_OR_METADATA_DRIFT: %',r.signature using errcode='55000'; end if;\n"
              " end loop;\n")


