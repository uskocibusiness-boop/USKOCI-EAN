def change(signature, old, new):
    assert after[signature].count(old) == 1, ("ANCHOR_DRIFT", signature, old[:80])
    after[signature] = after[signature].replace(old, new, 1)
    edits.append({"signature": signature, "before": old, "after": new})


def change_span(signature, start, end, new):
    body = after[signature]
    assert body.count(start) == 1 and body.count(end) == 1, ("SPAN_ANCHOR_DRIFT", signature, start[:60], end[:60])
    i = body.index(start)
    j = body.index(end, i)
    old = body[i:j]
    after[signature] = body[:i] + new + body[j:]
    edits.append({"signature": signature, "before": old, "after": new})


