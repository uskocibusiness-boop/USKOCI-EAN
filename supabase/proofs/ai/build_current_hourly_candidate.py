"""Derive R07 pricing from read-only, hash-equal 3 November source.

Reuses the existing reviewed transformations; never connects to any database.
The output is deliberately LOCAL_ONLY, not a deployable migration. It changes
nine current function bodies and adds no columns, privileges or certificates.
"""
from pathlib import Path
import hashlib
import json
import re
import runpy
import sys

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
TARGET = ROOT / 'supabase/candidates/r07_hourly_pricing_current.sql'
PRE = HERE / 'r07_current_hourly_preimage.json'
TRANSFORM = runpy.run_path(str(HERE / 'generate_hourly_candidate.py'))['transform']


def digest(value, algorithm='sha256'):
    return hashlib.new(algorithm, value.encode() if isinstance(value, str) else value).hexdigest()


def quote(value):
    return "'" + value.replace("'", "''") + "'"


def body(sql):
    match = re.search(r'\bAS (\$\w*\$)(.*?)\1;', sql, re.S)
    assert match, 'R07_CURRENT_FUNCTION_BODY_REQUIRED'
    return match[2]


def definition(entry):
    path = ROOT / entry['source']['path']
    raw = path.read_bytes()
    assert digest(raw) == entry['source']['sha256'], str(path) + ': source file changed'
    text = raw.decode('utf-8').replace('\r\n', '\n')
    pattern = r'CREATE OR REPLACE FUNCTION ' + re.escape(entry['name']) + r'\([^;]*?\bAS (\$\w*\$)(.*?)\1;'
    matches = [m[0] for m in re.finditer(pattern, text, re.S) if digest(m[2], 'md5') == entry['body_md5']]
    assert len(matches) == 1, entry['name'] + ': exact current body not unique'
    return matches[0]


def derive():
    capture = json.loads(PRE.read_text())
    assert capture['project_ref'] == 'leqcwgzvjsxugfgzdmth'
    assert capture['status'] == 'LOCAL_ONLY_NOT_DEPLOYED'
    assert len(capture['functions']) == 9 and len(capture['price_columns']) == 2
    before, after = {}, {}
    for entry in capture['functions']:
        name = entry['name']
        assert name not in before, name
        original = definition(entry)
        changed = TRANSFORM(name, original)
        assert changed != original
        before[name] = {**entry, 'definition': original}
        after[name] = {**entry, 'definition': changed, 'body_md5': digest(body(changed), 'md5')}
    dependencies = {e['name']: {**e, 'definition': definition(e)} for e in capture['unchanged_dependencies']}
    return {'capture': capture, 'before': before, 'after': after, 'dependencies': dependencies}


# Complete captured identity/security metadata, but never hosted OID assumptions.
# The postcondition below preserves the actual local OID and all other attributes.
def expected(functions):
    return {name: {k: v for k, v in f.items() if k not in ('source', 'definition', 'name')} for name, f in functions.items()}


CATALOG = """SELECT jsonb_object_agg(e.key,jsonb_build_object(
 'signature',p.oid::regprocedure::text,'body_md5',md5(replace(p.prosrc,chr(13),'')),
 'owner',pg_get_userbyid(p.proowner),'acl',p.proacl::text,'config',p.proconfig,
 'definer',p.prosecdef,'strict',p.proisstrict,'volatility',p.provolatile,'result',pg_get_function_result(p.oid)))
 FROM jsonb_each(expected) e LEFT JOIN pg_proc p ON p.oid=to_regprocedure(e.value->>'signature')"""


def generate():
    data = derive()
    pre = json.dumps(expected(data['before']), ensure_ascii=False, separators=(',', ':'))
    post = json.dumps(expected(data['after']), ensure_ascii=False, separators=(',', ':'))
    schema = []
    for c in data['capture']['price_columns']:
        schema.append(f"""IF NOT EXISTS(SELECT 1 FROM pg_attribute a
 WHERE a.attrelid={quote(c['table'])}::regclass AND a.attname='price_basis'
 AND a.atttypid='text'::regtype AND NOT a.attnotnull AND NOT a.attisdropped
 AND NOT a.atthasdef AND a.attgenerated=''
 AND EXISTS(SELECT 1 FROM pg_constraint k WHERE k.conrelid=a.attrelid
  AND k.conname={quote(c['constraint'])} AND k.convalidated
  AND pg_get_constraintdef(k.oid)={quote(c['constraint_definition'])}))
 THEN RAISE EXCEPTION 'R07_CURRENT_SCHEMA_DRIFT: %',{quote(c['table'])}; END IF;""")
    definitions = '\n'.join('EXECUTE $r07_definition$\n' + f['definition'] + '\n$r07_definition$;'
                            for f in data['after'].values())
    assert '$r07_definition$' not in ''.join(f['definition'] for f in data['after'].values())
    return f"""-- Generated by supabase/proofs/ai/build_current_hourly_candidate.py.
-- Captured current functions, already-expanded response schema, NO data backfill.
-- LOCAL_ONLY: not a migration, DEV operation packet, R01/R10 or release approval.
-- Nine existing bodies only. Preserve current cityless REMOTE, attention,
-- edit-resume and deadline behavior. Do not replay the older additive candidate.
DO $r07_current$
DECLARE
 expected jsonb := {quote(pre)}::jsonb;
 observed jsonb;
 prior_attributes jsonb;
 after_attributes jsonb;
 prior_path text := current_setting('search_path');
BEGIN
 IF current_setting('uskoci.r07_current.disposable',true) IS DISTINCT FROM 'LOCAL_ONLY'
    OR current_user <> 'postgres' THEN
  RAISE EXCEPTION 'R07_CURRENT_DISPOSABLE_REQUIRED';
 END IF;
 PERFORM set_config('search_path','pg_catalog',true);
 SELECT ({CATALOG}) INTO observed;
 IF observed IS DISTINCT FROM expected THEN RAISE EXCEPTION 'R07_CURRENT_SOURCE_OR_ACL_DRIFT'; END IF;
 {chr(10).join(schema)}
 SELECT jsonb_object_agg(p.oid::text,to_jsonb(p)-'prosrc') INTO prior_attributes
 FROM jsonb_each(expected) e JOIN pg_proc p ON p.oid=to_regprocedure(e.value->>'signature');
 {definitions}
 expected := {quote(post)}::jsonb;
 SELECT ({CATALOG}) INTO observed;
 IF observed IS DISTINCT FROM expected THEN RAISE EXCEPTION 'R07_CURRENT_POSTIMAGE_MISMATCH'; END IF;
 SELECT jsonb_object_agg(p.oid::text,to_jsonb(p)-'prosrc') INTO after_attributes
 FROM jsonb_each(expected) e JOIN pg_proc p ON p.oid=to_regprocedure(e.value->>'signature');
 IF after_attributes IS DISTINCT FROM prior_attributes THEN RAISE EXCEPTION 'R07_CURRENT_METADATA_CHANGED'; END IF;
 PERFORM set_config('search_path',prior_path,true);
END;
$r07_current$;
"""


if __name__ == '__main__':
    args = sys.argv[1:]
    if args == ['--json']:
        print(json.dumps(derive(), ensure_ascii=False))
    elif args == ['--check']:
        assert TARGET.read_text() == generate(), 'R07_CURRENT_GENERATED_SOURCE_DRIFT'
        print('R07_CURRENT_SOURCE_PASS: 9 current bodies; existing schema preserved; no deployment')
    else:
        assert not args, 'Only --check or --json is supported'
        TARGET.write_text(generate(), encoding='utf-8', newline='\n')
        print('Generated LOCAL_ONLY current hourly candidate; no database connection')
